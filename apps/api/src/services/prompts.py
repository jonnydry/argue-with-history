def get_persona_prompt(figure: str, topic_id: str | None = None) -> str:
    from ..models.figures import FIGURES_DATA
    from ..models.schemas import Figure

    base = PERSONAS.get(figure, "")
    if not topic_id:
        return base
    try:
        fig_enum = Figure(figure)
        figure_info = FIGURES_DATA.get(fig_enum)
        if figure_info:
            for t in figure_info.topics:
                if t.id == topic_id and getattr(t, "prompt_hint", None):
                    return f"{base}\n\nTOPIC FOCUS: {t.prompt_hint}"
    except (ValueError, TypeError):
        pass
    return base
